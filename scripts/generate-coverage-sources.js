#!/usr/bin/env node
/**
 * Write a Karma spec that imports every application source under src/app.
 * Istanbul only instruments modules the test bundle loads. Without this,
 * coverage reports the few files specs already import and hides the rest.
 */
const fs = require('fs');
const path = require('path');

const appRoot = path.join(__dirname, '..', 'src', 'app');
const outFile = path.join(appRoot, 'coverage-sources.spec.ts');

function walk(dir, found) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(full, found);
      continue;
    }
    if (!entry.name.endsWith('.ts') || entry.name.endsWith('.spec.ts')) {
      continue;
    }
    found.push(full);
  }
}

const files = [];
walk(appRoot, files);
files.sort();

const imports = files.map((file) => {
  let rel = path.relative(appRoot, file).replace(/\\/g, '/').replace(/\.ts$/, '');
  if (!rel.startsWith('.')) {
    rel = './' + rel;
  }
  return `import '${rel}';`;
});

const body = `// Generated by scripts/generate-coverage-sources.js. Do not edit.
// Imports every src/app TypeScript module so Istanbul coverage includes files no spec imports.
${imports.join('\n')}

describe('application source coverage', () => {
  it('loads every src/app TypeScript module', () => {
    expect(${files.length}).toBeGreaterThan(0);
  });
});
`;

fs.writeFileSync(outFile, body);
console.log(`Wrote ${files.length} source imports to ${path.relative(process.cwd(), outFile)}`);
